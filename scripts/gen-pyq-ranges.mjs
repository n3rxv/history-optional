/**
 * Generates lib/pyqSectionRanges.ts from lib/pyqData.ts.
 *
 * The dashboard needs to bucket a reader's attempted PYQ ids by section. It
 * could import pyqData and read `.section` off each question, but that file is
 * 608 KB of question text and the dashboard needs none of it -- the same
 * mistake supabase/flashcards.sql records fixing for the flashcard deck, where
 * every card's text was being shipped to every visitor.
 *
 * Question ids fall into contiguous runs by section, so the whole lookup
 * compresses to about 400 characters.
 *
 *   node scripts/gen-pyq-ranges.mjs           rewrite the file
 *   node scripts/gen-pyq-ranges.mjs --check   fail if it is out of date
 *
 * The check runs in `npm run build`, so adding questions without regenerating
 * cannot silently leave the dashboard reporting stale totals.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

// tsx's CommonJS hook, rather than the ESM one: the ESM loader now wants
// --import on the node command line, and this script has to stay runnable as
// a plain `node scripts/...` from package.json.
const require = createRequire(import.meta.url);
require('tsx/cjs');
const { pyqs } = require('../lib/pyqData.ts');

const sorted = [...pyqs].sort((a, b) => a.id - b.id);
const runs = [];
for (const q of sorted) {
  const last = runs[runs.length - 1];
  if (last && last.section === q.section && last.to === q.id - 1) last.to = q.id;
  else runs.push({ section: q.section, from: q.id, to: q.id });
}

const sections = [...new Set(sorted.map((q) => q.section))];
const bySection = Object.fromEntries(
  sections.map((s) => [s, runs.filter((r) => r.section === s).map((r) => [r.from, r.to])]),
);
const totals = Object.fromEntries(
  sections.map((s) => [s, sorted.filter((q) => q.section === s).length]),
);

const body = `// Generated by scripts/gen-pyq-ranges.mjs -- do not edit by hand.
//
// Which section each PYQ id belongs to, as inclusive id ranges, so the
// dashboard can bucket a reader's attempted ids without importing the 608 KB
// of question text in lib/pyqData.ts.

export const PYQ_SECTION_RANGES: Record<string, [number, number][]> = ${JSON.stringify(bySection, null, 2)};

export const PYQ_SECTION_TOTALS: Record<string, number> = ${JSON.stringify(totals, null, 2)};

export const PYQ_TOTAL = ${sorted.length};

/** The section an id belongs to, or null if it is not a known question. */
export function sectionForPyq(id: number): string | null {
  for (const [section, ranges] of Object.entries(PYQ_SECTION_RANGES)) {
    for (const [from, to] of ranges) if (id >= from && id <= to) return section;
  }
  return null;
}
`;

const target = new URL('../lib/pyqSectionRanges.ts', import.meta.url);

if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(target, 'utf8'); } catch { /* missing counts as stale */ }
  if (current !== body) {
    console.error('\nlib/pyqSectionRanges.ts is out of date with lib/pyqData.ts.');
    console.error('Run: node scripts/gen-pyq-ranges.mjs\n');
    process.exit(1);
  }
  process.exit(0);
}

writeFileSync(target, body);
console.log(`wrote lib/pyqSectionRanges.ts — ${sorted.length} questions, ${runs.length} runs, ${sections.length} sections`);
